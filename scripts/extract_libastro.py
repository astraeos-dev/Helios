"""Extract the data tables of the astro library from libastro's C sources.

libastro is the C library inside PyEphem (MIT license). Run with the libastro
folder of a PyEphem source distribution, such as ephem-4.2.1/libastro:

    python scripts/extract_libastro.py path/to/libastro

It rewrites the _*_data.py modules of custom_components/astraeos_helios/astro.
"""

from __future__ import annotations

from pathlib import Path
import re
import sys

ASTRO = (
    Path(__file__).resolve().parents[1]
    / "custom_components"
    / "astraeos_helios"
    / "astro"
)
SOURCE = "libastro from PyEphem 4.2.1 (MIT license, see LICENSE.txt)"
NUMBER = r"[-+]?\d+(?:\.\d*)?(?:[eE][-+]?\d+)?"


def block(text: str, start: str) -> str:
    """Return the body of the C initializer that follows start, up to its '};'."""
    begin = text.index(start)
    return text[text.index("{", begin) + 1 : text.index("};", begin)]


def rows(body: str, width: int) -> list[tuple[str, ...]]:
    """Return the {a, b, ...} rows of a C initializer body, comments removed."""
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    found = re.findall(r"\{([^{}]*)\}", body)
    parsed = [
        tuple(item.strip() for item in row.split(",") if item.strip()) for row in found
    ]
    return [row for row in parsed if len(row) == width]


def numbers(body: str) -> list[str]:
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    return re.findall(NUMBER, body)


def write(name: str, docstring: str, assignments: list[tuple[str, str, str]]) -> None:
    lines = [
        f'"""{docstring}\n\nGenerated by scripts/extract_libastro.py from {SOURCE}. Do not edit."""',
        "",
    ]
    for comment, variable, value in assignments:
        lines += ["", f"# {comment}", f"{variable} = {value}"]
    (ASTRO / name).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def tuple_lines(items: list[str], per_line: int = 1) -> str:
    chunks = [
        ", ".join(items[i : i + per_line]) for i in range(0, len(items), per_line)
    ]
    return "(\n" + "".join(f"    {chunk},\n" for chunk in chunks) + ")"


def vsop87(src: Path) -> None:
    text = (src / "vsop87_data.c").read_text(encoding="latin-1")
    terms = rows(block(text, "double vx_earth[][3]"), 3)
    starts = [
        tuple(int(x) for x in row) for row in rows(block(text, "int vn_earth[][3]"), 3)
    ]
    starts.append((0, 0, 0))  # the C table ends with a zeroed row
    series = []
    for coordinate in range(3):
        powers = []
        alpha = 0
        while starts[alpha + 1][coordinate]:
            first, last = starts[alpha][coordinate], starts[alpha + 1][coordinate]
            powers.append(
                "(\n"
                + "".join(
                    f"        ({float(a)!r}, {float(b)!r}, {float(c)!r}),\n"
                    for a, b, c in terms[first:last]
                )
                + "    )"
            )
            alpha += 1
        series.append("(\n" + "".join(f"    {power},\n" for power in powers) + ")")
    write(
        "_vsop87_earth_data.py",
        "VSOP87D series of the Earth: heliocentric ecliptic and equinox of date.\n\n"
        "Bretagnon & Francou (1988), as truncated in libastro. Each power of time is a\n"
        "tuple of (A, B, C) terms, A * cos(B + C * t) with t in Julian millennia from\n"
        "J2000.0 (TT) and A scaled by 1e8: radians for L and B, AU for R.",
        [
            ("Heliocentric longitude", "L", series[0]),
            ("Heliocentric latitude", "B", series[1]),
            ("Radius vector", "R", series[2]),
        ],
    )


def nutation(src: Path) -> None:
    text = (src / "nutation.c").read_text(encoding="latin-1")
    delaunay = rows(block(text, "static double delaunay[5][4]"), 4)
    multipliers = rows(block(text, "static short multarg[NUT_SERIES][5]"), 5)
    secular = rows(block(text, "static long ampsecul[][5]"), 5)
    constant = rows(block(text, "static short ampconst[NUT_SERIES][2]"), 2)
    assert (len(delaunay), len(multipliers), len(constant)) == (5, 106, 106)
    fmt = lambda row: "(" + ", ".join(row) + ")"  # noqa: E731
    write(
        "_nutation_data.py",
        "IAU 1980 nutation series, in units of 0.0001 arcsecond.",
        [
            (
                "Delaunay arguments M', M, F, D, Omega in arcseconds: c0 + c1 T + c2 T^2 + c3 T^3",
                "DELAUNAY",
                tuple_lines([fmt(row) for row in delaunay]),
            ),
            (
                "Multipliers of the Delaunay arguments, one row per term",
                "MULTIPLIERS",
                tuple_lines([fmt(r) for r in multipliers]),
            ),
            (
                "Terms with secular amplitudes: index, dpsi, dpsi per T/10, deps, deps per T/10",
                "SECULAR_TERMS",
                tuple_lines([fmt(row) for row in secular]),
            ),
            (
                "Constant amplitudes (dpsi, deps); (0, 0) where SECULAR_TERMS has the term",
                "CONSTANT_TERMS",
                tuple_lines([fmt(r) for r in constant]),
            ),
        ],
    )


def deltat(src: Path) -> None:
    text = (src / "deltat.c").read_text(encoding="latin-1")
    tab_start = int(re.search(r"#define TABSTART (\d+)", text).group(1))
    tab_end = int(re.search(r"#define TABEND (\d+)", text).group(1))
    m_s = numbers(block(text, "short m_s[MS_SIZ]"))
    dt = numbers(block(text, "short dt[TABSIZ]"))
    assert len(m_s) == 28 and len(dt) == tab_end - tab_start + 1
    write(
        "_deltat_data.py",
        "Delta T = TT - UT tables: Morrison & Stephenson (2004) and the Astronomical Almanac.",
        [
            (
                "First and last years of TABLE",
                "TABLE_START, TABLE_END",
                f"{tab_start}, {tab_end}",
            ),
            (
                "Delta T at the start of each year, in hundredths of a second",
                "TABLE",
                tuple_lines(dt, 10),
            ),
            (
                "Delta T every 100 years from -1000 to 1700, in seconds",
                "HISTORIC",
                tuple_lines(m_s, 10),
            ),
        ],
    )


def constellations(src: Path) -> None:
    text = (src / "constel.c").read_text(encoding="latin-1")
    names = re.findall(
        r'"(\w+): ([^"]+)"', block(text, "static char *cns_namemap[ NCNS ]")
    )
    bounds = rows(block(text, "} cbound[ NBOUNDS ]"), 4)
    start = numbers(block(text, "static short start[]"))
    assert len(bounds) == 357 and len(start) == 37
    write(
        "_constellation_data.py",
        "IAU constellation boundaries (Delporte 1930) for the equinox of B1875.0.\n\n"
        "Transcribed by Rappaport, method of Roman (1987, PASP 99, 695).",
        [
            (
                "Abbreviation and name of each constellation",
                "NAMES",
                "{\n" + "".join(f'    "{a}": "{n}",\n' for a, n in names) + "}",
            ),
            (
                "Lower RA, upper RA (hours * 1800), lower declination (degrees * 60), constellation",
                "BOUNDS",
                tuple_lines(
                    [f'({lo}, {hi}, {dec}, "{abbr}")' for lo, hi, dec, abbr in bounds]
                ),
            ),
            (
                "First row of BOUNDS to search, by declination band of 5 degrees from -90",
                "START",
                tuple_lines(start, 12),
            ),
        ],
    )


if __name__ == "__main__":
    source = Path(sys.argv[1])
    vsop87(source)
    nutation(source)
    deltat(source)
    constellations(source)
    print("wrote", ", ".join(sorted(p.name for p in ASTRO.glob("_*_data.py"))))
